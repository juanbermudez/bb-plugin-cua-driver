#!/usr/bin/env node
/**
 * Regenerates src/upstream-schemas.generated.ts from the cua-driver installed on
 * this machine, by asking its MCP server for tools/list. Run after updating
 * cua-driver (`npm run sync:schemas`), then review the diff: it is the exact
 * change in what agents will be able to send.
 *
 * Property descriptions are cut to their first sentence: every schema is in
 * every agent session's prompt, and the full upstream prose runs to pages.
 */
import { execFileSync, spawn } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { createInterface } from "node:readline";
import { fileURLToPath } from "node:url";

const DESCRIPTION_LIMIT = 200;
const binary = process.env.CUA_DRIVER_BIN ?? "cua-driver";
const outputPath = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "upstream-schemas.generated.ts");

function firstSentence(text) {
  const flat = String(text).replace(/\s+/g, " ").trim();
  const sentence = /^(.+?[.!?])(\s|$)/.exec(flat)?.[1] ?? flat;
  return sentence.length > DESCRIPTION_LIMIT ? `${sentence.slice(0, DESCRIPTION_LIMIT - 1)}…` : sentence;
}

function compact(schema) {
  if (Array.isArray(schema)) return schema.map(compact);
  if (schema === null || typeof schema !== "object") return schema;
  const out = {};
  for (const key of Object.keys(schema).sort()) {
    const value = schema[key];
    if (key === "description" && typeof value === "string") out[key] = firstSentence(value);
    else if (key === "examples") continue;
    else out[key] = compact(value);
  }
  return out;
}

function listTools() {
  return new Promise((resolve, reject) => {
    const child = spawn(binary, ["mcp"], { stdio: ["pipe", "pipe", "inherit"] });
    const pending = new Map();
    let nextId = 1;
    const send = (method, params) =>
      new Promise((done, fail) => {
        const id = nextId++;
        pending.set(id, { done, fail });
        child.stdin.write(`${JSON.stringify({ jsonrpc: "2.0", id, method, params })}\n`);
      });
    createInterface({ input: child.stdout }).on("line", (line) => {
      let message;
      try {
        message = JSON.parse(line);
      } catch {
        return;
      }
      const waiter = pending.get(message.id);
      if (waiter === undefined) return;
      pending.delete(message.id);
      if (message.error) waiter.fail(new Error(message.error.message ?? "MCP error"));
      else waiter.done(message.result);
    });
    child.once("error", reject);
    (async () => {
      await send("initialize", {
        protocolVersion: "2025-06-18",
        capabilities: {},
        clientInfo: { name: "bb-plugin-cua-driver-sync", version: "0" },
      });
      child.stdin.write(`${JSON.stringify({ jsonrpc: "2.0", method: "notifications/initialized", params: {} })}\n`);
      const tools = [];
      let cursor;
      do {
        const result = await send("tools/list", cursor === undefined ? {} : { cursor });
        tools.push(...(result.tools ?? []));
        cursor = typeof result.nextCursor === "string" ? result.nextCursor : undefined;
      } while (cursor !== undefined);
      return tools;
    })().then(
      (tools) => {
        child.kill();
        resolve(tools);
      },
      (error) => {
        child.kill();
        reject(error);
      },
    );
  });
}

const version = /(\d+\.\d+\.\d+)/.exec(execFileSync(binary, ["--version"], { encoding: "utf8" }))?.[1];
if (version === undefined) throw new Error("could not read the cua-driver version");
const tools = await listTools();
const schemas = Object.fromEntries(
  tools
    .map((tool) => [tool.name, compact(tool.inputSchema ?? { type: "object" })])
    .sort(([a], [b]) => a.localeCompare(b)),
);
writeFileSync(
  outputPath,
  [
    `// Generated by scripts/sync-upstream-schemas.mjs from cua-driver ${version}. Do not edit by hand.`,
    `export const UPSTREAM_DRIVER_VERSION = ${JSON.stringify(version)};`,
    "",
    `export const UPSTREAM_SCHEMAS: Readonly<Record<string, Record<string, unknown>>> = ${JSON.stringify(schemas, null, 2)};`,
    "",
  ].join("\n"),
);
console.log(`wrote ${tools.length} tool schemas from cua-driver ${version} to ${outputPath}`);
